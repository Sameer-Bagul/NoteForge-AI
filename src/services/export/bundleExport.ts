import { Notebook, VideoNotes, TopicNotes, QuizQuestion, InterviewQuestion } from '@/types';
import { tauriApi, isTauri } from '../tauri';
import JSZip from 'jszip';

export interface BundleExportResult {
  success: boolean;
  cancelled?: boolean;
  path?: string;
  isZipFallback?: boolean;
  message?: string;
}

function sanitizeFilename(name: string): string {
  return name
    .replace(/[^a-zA-Z0-9_\-\s]/g, '')
    .trim()
    .replace(/\s+/g, '_')
    .slice(0, 60) || 'Untitled';
}

function pad(num: number, size = 2): string {
  return num.toString().padStart(size, '0');
}

export function generateNotebookBundleFiles(data: Notebook | VideoNotes): {
  folderName: string;
  files: Record<string, string>;
} {
  const title = (data.title || 'Study Notebook').trim();
  const folderName = sanitizeFilename(title) || 'Study_Vault';
  const files: Record<string, string> = {};

  // Extract topics
  let topics: TopicNotes[] = [];
  if ('chapters' in data && Array.isArray((data as Notebook).chapters)) {
    topics = (data as Notebook).chapters.flatMap(c => c.topics || []);
  } else if ('notes' in data && Array.isArray((data as VideoNotes).notes)) {
    topics = (data as VideoNotes).notes;
  }

  // Create chapters filenames list for README navigation
  const chapterEntries: Array<{ title: string; filename: string; relPath: string }> = [];

  let diagramCounter = 1;
  const diagramFiles: Record<string, string> = {};

  topics.forEach((t, i) => {
    const rawTitle = t.title || t.topicTitle || `Topic ${i + 1}`;
    const filename = `${pad(i + 1)}_${sanitizeFilename(rawTitle)}.md`;
    const relPath = `01_Chapters/${filename}`;
    chapterEntries.push({ title: rawTitle, filename, relPath });

    // Extract any mermaid diagrams for standalone .mmd export
    const content = t.content || '';
    const mermaidRegex = /```mermaid\s*([\s\S]*?)```/g;
    let match;
    while ((match = mermaidRegex.exec(content)) !== null) {
      const diagramCode = match[1].trim();
      const diagName = `diagram_${pad(diagramCounter++)}_${sanitizeFilename(rawTitle)}.mmd`;
      diagramFiles[`03_Diagrams/${diagName}`] = diagramCode;
    }
  });

  // Build README.md
  const readmeLines: string[] = [
    `# ${title}`,
    '',
    `> Generated by **NoteForge AI** • ${new Date().toLocaleDateString(undefined, { dateStyle: 'long' })}`,
    '',
    '---',
    '',
    '## Curriculum & Table of Contents',
    '',
  ];

  if (chapterEntries.length > 0) {
    chapterEntries.forEach((entry, idx) => {
      readmeLines.push(`${idx + 1}. [${entry.title}](${entry.relPath})`);
    });
  } else {
    readmeLines.push('*No chapters defined in this notebook.*');
  }

  readmeLines.push('');
  readmeLines.push('---');
  readmeLines.push('');
  readmeLines.push('## Vault Navigation');
  readmeLines.push('');
  readmeLines.push('- **Chapters Folder**: [`01_Chapters/`](01_Chapters/) — In-depth, textbook-grade study notes with code examples and timestamps.');
  
  const hasQuiz = Array.isArray(data.quiz) && data.quiz.length > 0;
  const hasInterview = Array.isArray(data.interviewQA) && data.interviewQA.length > 0;

  if (hasQuiz || hasInterview) {
    readmeLines.push('- **Exercises & Assessments**: [`02_Exercises/`](02_Exercises/) — Active recall practice and interview preparation:');
    if (hasQuiz) {
      readmeLines.push('  - [Self-Check Quiz](02_Exercises/quiz.md)');
    }
    if (hasInterview) {
      readmeLines.push('  - [Technical Interview QA](02_Exercises/interview_qa.md)');
    }
  }

  if (Object.keys(diagramFiles).length > 0) {
    readmeLines.push('- **Diagram Assets**: [`03_Diagrams/`](03_Diagrams/) — Raw Mermaid `.mmd` diagrams for previewing in Obsidian, VS Code, or Mermaid Live.');
  }

  files['README.md'] = readmeLines.join('\n');

  // Build Individual Chapter Files
  topics.forEach((t, i) => {
    const rawTitle = t.title || t.topicTitle || `Topic ${i + 1}`;
    const entry = chapterEntries[i];
    const prev = i > 0 ? chapterEntries[i - 1] : null;
    const next = i < chapterEntries.length - 1 ? chapterEntries[i + 1] : null;

    const chapterLines: string[] = [
      `# ${rawTitle}`,
      '',
    ];

    if (t.timeDisplay || t.startTime !== undefined) {
      chapterLines.push(`> **Video Anchor**: \`[${t.timeDisplay || '0:00'}]\``);
      chapterLines.push('');
    }

    if (t.summary && t.summary !== rawTitle) {
      chapterLines.push(`> **Overview**: ${t.summary}`);
      chapterLines.push('');
    }

    const bodyContent = (t.content || '').trim();
    if (bodyContent) {
      chapterLines.push(bodyContent);
      chapterLines.push('');
    }

    if (Array.isArray(t.keyTakeaways) && t.keyTakeaways.length > 0) {
      chapterLines.push('### Key Takeaways');
      chapterLines.push('');
      t.keyTakeaways.forEach(k => {
        chapterLines.push(`- ${k}`);
      });
      chapterLines.push('');
    }

    // Navigation footer
    chapterLines.push('---');
    chapterLines.push('');
    const navParts: string[] = [];
    if (prev) {
      navParts.push(`[← Previous: ${prev.title}](${prev.filename})`);
    }
    navParts.push(`[Table of Contents](../README.md)`);
    if (next) {
      navParts.push(`[Next: ${next.title} →](${next.filename})`);
    }
    chapterLines.push(navParts.join(' • '));
    chapterLines.push('');

    files[entry.relPath] = chapterLines.join('\n');
  });

  // Build 02_Exercises/quiz.md
  if (hasQuiz) {
    const quizLines: string[] = [
      `# Self-Check Quiz: ${title}`,
      '',
      `> Test your understanding across the topics. Click to reveal answers and explanations.`,
      '',
      '---',
      '',
    ];

    (data.quiz as QuizQuestion[]).forEach((q, idx) => {
      quizLines.push(`### Question ${idx + 1} (${q.difficulty?.toUpperCase() || 'GENERAL'})`);
      quizLines.push('');
      quizLines.push(`**Topic**: ${q.topic || 'General'}`);
      quizLines.push('');
      quizLines.push(q.question);
      quizLines.push('');

      if (Array.isArray(q.options) && q.options.length > 0) {
        q.options.forEach(opt => {
          quizLines.push(`- ${opt}`);
        });
        quizLines.push('');
      }

      quizLines.push('<details>');
      quizLines.push('<summary><b>Reveal Correct Answer & Explanation</b></summary>');
      quizLines.push('');
      quizLines.push(`**Correct Answer**: \`${q.answer}\``);
      quizLines.push('');
      if (q.explanation) {
        quizLines.push(`**Explanation**: ${q.explanation}`);
        quizLines.push('');
      }
      quizLines.push('</details>');
      quizLines.push('');
      quizLines.push('---');
      quizLines.push('');
    });

    files['02_Exercises/quiz.md'] = quizLines.join('\n');
  }

  // Build 02_Exercises/interview_qa.md
  if (hasInterview) {
    const interviewLines: string[] = [
      `# Technical Interview Questions: ${title}`,
      '',
      `> Key conceptual and practical interview questions synthesized from this curriculum.`,
      '',
      '---',
      '',
    ];

    (data.interviewQA as InterviewQuestion[]).forEach((iq, idx) => {
      interviewLines.push(`### Q${idx + 1}: ${iq.question}`);
      interviewLines.push('');
      interviewLines.push(`- **Category**: \`${iq.category || 'technical'}\` • **Target Level**: \`${iq.difficulty || 'mid'}\``);
      interviewLines.push('');
      interviewLines.push('<details open>');
      interviewLines.push('<summary><b>Model Answer</b></summary>');
      interviewLines.push('');
      interviewLines.push(iq.answer);
      if (iq.followUp) {
        interviewLines.push('');
        interviewLines.push(`> **Interviewer Follow-up Question**: ${iq.followUp}`);
      }
      interviewLines.push('');
      interviewLines.push('</details>');
      interviewLines.push('');
      interviewLines.push('---');
      interviewLines.push('');
    });

    files['02_Exercises/interview_qa.md'] = interviewLines.join('\n');
  }

  // Merge diagrams
  Object.assign(files, diagramFiles);

  return { folderName, files };
}

export async function exportNotebookAsFolder(
  data: Notebook | VideoNotes
): Promise<BundleExportResult> {
  const { folderName, files } = generateNotebookBundleFiles(data);

  // 1. Native Desktop Tauri Flow: Use native directory dialog + Rust exporter
  if (isTauri()) {
    try {
      const chosenBasePath = await tauriApi.pickDirectory();
      if (!chosenBasePath) {
        return { success: false, cancelled: true };
      }

      const createdPath = await tauriApi.exportNotebookFolder(chosenBasePath, folderName, files);
      return {
        success: true,
        path: createdPath,
        message: `Vault exported to ${createdPath}`,
      };
    } catch (err: any) {
      console.error('Tauri folder export failed, falling back:', err);
    }
  }

  // 2. Web Browser Flow: Try HTML5 File System Access API (window.showDirectoryPicker)
  if (typeof window !== 'undefined' && 'showDirectoryPicker' in window) {
    try {
      const rootHandle = await (window as any).showDirectoryPicker({
        mode: 'readwrite',
        startIn: 'documents',
      });

      // Create target directory
      const folderHandle = await rootHandle.getDirectoryHandle(folderName, { create: true });

      for (const [relPath, content] of Object.entries(files)) {
        const parts = relPath.split('/');
        let curDir = folderHandle;

        for (let i = 0; i < parts.length - 1; i++) {
          curDir = await curDir.getDirectoryHandle(parts[i], { create: true });
        }

        const fileName = parts[parts.length - 1];
        const fileHandle = await curDir.getFileHandle(fileName, { create: true });
        const writable = await fileHandle.createWritable();
        await writable.write(content);
        await writable.close();
      }

      return {
        success: true,
        path: folderName,
        message: `Study vault saved to folder "${folderName}"`,
      };
    } catch (err: any) {
      if (err?.name === 'AbortError') {
        return { success: false, cancelled: true };
      }
      console.warn('Web File System Access API unavailable or denied, falling back to ZIP:', err);
    }
  }

  // 3. Universal Fallback: Download as structured ZIP bundle
  try {
    const zip = new JSZip();
    for (const [relPath, content] of Object.entries(files)) {
      zip.file(`${folderName}/${relPath}`, content);
    }

    const zipBlob = await zip.generateAsync({ type: 'blob' });
    const url = URL.createObjectURL(zipBlob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${folderName}.zip`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    return {
      success: true,
      isZipFallback: true,
      message: `Downloaded as structured archive "${folderName}.zip"`,
    };
  } catch (zipErr: any) {
    console.error('ZIP generation failed:', zipErr);
    return {
      success: false,
      message: zipErr?.message || 'Could not export folder bundle.',
    };
  }
}

